    const id = winter ? (r < 0.42 ? "sunny" : r < 0.52 ? "blossom" : r < 0.7 ? "rainy" : "snowy") : r < 0.5 ? "sunny" : r < 0.75 ? "blossom" : "rainy";
    return { id, slot, ...WEATHERS[id] };
